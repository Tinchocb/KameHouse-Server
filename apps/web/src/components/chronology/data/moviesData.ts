function movieMetaToVolumeData(meta: MovieChronologyMeta, index: number): VolumeData {
  const lore = DRAGON_BALL_MOVIES_LORE[meta.loreId] || {
    id: meta.loreId,
    title: `Película ${meta.loreId}`,
    era: meta.seriesTag,
    canonStatus: meta.isCanonMovie ? 'Canónico' : 'No canónico',
    chronologyNotes: 'Especial cinematográfico de Dragon Ball.',
    antagonists: [],
    keyEvents: [],
    newCharacters: [],
    specialTrivia: '',
  };

  const tmdbId = LORE_ID_TO_TMDB[meta.loreId];
  const isSpecial = meta.mediaType === 'SPECIAL';

  return {
    id: `movie-${meta.loreId}`,
    volumeNumber: isSpecial ? 'Especial' : 'Película',
    volumeIndex: 100 + index,
    seriesTag: meta.seriesTag,
    seriesId: meta.seriesId,
    sagaId: 'peliculas-especiales',
    sagaLabel: isSpecial ? 'Especial de TV' : 'Película',
    order: meta.order,
    title: lore.title,
    subtitle: lore.chronologyNotes || (isSpecial ? 'Especial cinematográfico' : 'Largometraje'),
    episodesRange: isSpecial ? 'Especial TV' : 'Película',
    episodesCount: 1,
    officialYear: meta.officialYear,
    officialYearNumber: meta.officialYearNumber,
    saga: meta.seriesId === 'classic' ? 'clasico' : meta.seriesId === 'super' ? 'super' : meta.seriesId === 'gt' ? 'gt' : 'saiyan-freezer',
    coverArt: {
      dominantToneDescription: isSpecial ? 'Aura dorada de especial histórico' : 'Tono cinematográfico de alta definición',
      visualSummary: lore.chronologyNotes || lore.title,
      kanjiTitle: meta.symbolGlyph,
      kanjiSubtitle: isSpecial ? '特別編' : '劇場版',
      symbolGlyph: meta.symbolGlyph,
      auraGradient: meta.seriesId === 'super'
        ? 'from-cyan-950 via-blue-950 to-neutral-950'
        : meta.seriesId === 'z'
          ? 'from-red-950 via-amber-950 to-neutral-950'
          : 'from-amber-950 via-stone-900 to-neutral-950',
      spineColor: meta.accentHex,
      borderColor: `border-[${meta.accentHex}]/50`,
      badgeBg: 'bg-white/10 text-white border-white/20',
      tagColor: 'text-brand-accent',
      accentHex: meta.accentHex,
      themeClass: `theme-${meta.seriesId}`,
    },
    narrative: {
      detonante: {
        title: 'Contexto Temporal',
        description: lore.chronologyNotes || 'Suceso acontecido en esta época de la historia.',
        statusQuoBreaker: lore.canonStatus,
        exactEpisodePoint: lore.seriesContext ? `Era ${lore.era}` : meta.officialYear,
      },
      climax: {
        title: 'Batalla Decisiva',
        description: lore.keyEvents?.[lore.keyEvents.length - 1] || lore.title,
        decisiveBattle: lore.antagonists && lore.antagonists.length > 0 ? lore.antagonists.join(', ') : 'Enfrentamiento épico',
        forbiddenTechniqueOrCost: lore.canonStatus,
        iconicMoment: lore.keyEvents?.[0] || lore.title,
      },
      lore: {
        title: 'Curiosidades y Canon',
        secretSummary: lore.specialTrivia || lore.chronologyNotes || '',
        cosmicBackground: lore.canonStatus,
        deityInvolved: lore.era,
        cosmicImpact: meta.isCanonMovie ? 'Línea Canónica Oficial' : 'Multiverso / Continuidad Alternativa',
        unrevealedFact: lore.specialTrivia || '',
      },
      characters: lore.newCharacters || [],
      keyArtifacts: [],
    },
    detailedStory: {
      prologue: lore.chronologyNotes || '',
      escalation: lore.keyEvents?.[0] || '',
      turningPoint: lore.keyEvents?.[1] || '',
      aftermath: lore.keyEvents?.[lore.keyEvents.length - 1] || '',
      keyBattles: (lore.antagonists || []).map((ant) => ({
        fighter1: 'Guerreros Z',
        fighter2: ant,
        outcome: 'Victoria tras combate decisivo',
      })),
      episodeMilestones: (lore.keyEvents || []).map((evt, evtIdx) => ({
        episode: isSpecial ? `Hito ${evtIdx + 1}` : `Momento ${evtIdx + 1}`,
        title: evt,
        synopsis: evt,
        characterFocus: lore.newCharacters?.[evtIdx] || lore.title,
        iconEmoji: isSpecial ? '⚡' : '🎬',
      })),
    },
    characters: lore.newCharacters || [],
    keyArtifacts: [],
    tmdbId,
    canonStatus: meta.isCanonMovie ? 'CANON' : 'NON_CANON',
    importance: meta.isCanonMovie ? 'MUST_WATCH' : 'OPTIONAL',
    threatLevel: meta.isCanonMovie ? 'Canónico Oficial' : 'Multiverso Alternativo',
    isMovie: true,
    mediaType: meta.mediaType,
    isCanonMovie: meta.isCanonMovie,
  };
}

/** Catálogo completo de películas y especiales adaptados a la línea de tiempo */
export const CHRONOLOGY_MOVIES_DATA: VolumeData[] = MOVIES_METADATA_TABLE.map(movieMetaToVolumeData);

/**
 * Devuelve las películas y especiales que corresponden al filtro seleccionado:
 * - 'none': ninguna película (solo las 35 series de TV)
 * - 'canon': solo los especiales canónicos y películas canónicas (Bardock, Trunks, Broly, Super Hero, Dioses, Freezer)
 * - 'all': todas las 26 películas y especiales incluyendo las de la época dorada de DBZ
 */
export function getMoviesForFilter(filter: MovieFilterOption): VolumeData[] {
  if (filter === 'none') return [];
  if (filter === 'canon') return CHRONOLOGY_MOVIES_DATA.filter((m) => m.isCanonMovie);
  return CHRONOLOGY_MOVIES_DATA;
}
