func TestShimHelpTarget(t *testing.T) {
	help := "This is a shim, generated by Chocolatey's ShimGenerator (shimgen).\r\n Target: 'C:\\Program Files\\ffmpeg\\ffprobe.exe'\r\n command (optional): ''\r\n"
	if got := shimHelpTarget(help); got != `C:\Program Files\ffmpeg\ffprobe.exe` {
		t.Fatalf("target = %q", got)
	}
	if got := shimHelpTarget(strings.ReplaceAll(help, "command (optional): ''", "command (optional): '-extra'")); got != "" {
		t.Fatalf("must preserve a shim with injected arguments, got %q", got)
	}
	if got := shimHelpTarget("Target: 'C:\\ffprobe.exe'"); got != "" {
		t.Fatalf("accepted non-shim output: %q", got)
	}
}

func TestResolveLeavesOrdinaryExecutablesUntouched(t *testing.T) {
	path := filepath.Join(t.TempDir(), "ffprobe.exe")
	if err := os.WriteFile(path, []byte("MZ ordinary binary"), 0600); err != nil {
		t.Fatal(err)
	}
	if got := resolveToolExecutable(path); got != path {
		t.Fatalf("got %q, want %q", got, path)
	}
}

// Explicit opt-in: uses installed tools, but only a synthetic loopback source.
// The default suite does not depend on Chocolatey or contact Drive.
func TestInstalledChocolateyToolsCancelPromptly(t *testing.T) {
	dir := os.Getenv("KAMEHOUSE_TEST_CHOCOLATEY_BIN")
	if dir == "" {
		t.Skip("set KAMEHOUSE_TEST_CHOCOLATEY_BIN to exercise installed shims")
	}
	t.Setenv("PATH", dir)
	for _, tool := range []string{"ffprobe", "ffmpeg"} {
		t.Run(tool, func(t *testing.T) {
			shim := filepath.Join(dir, tool+".exe")
			if !isChocolateyShim(shim) {
				t.Fatalf("not a recognized Chocolatey shim: %s", shim)
			}
			resolve := ResolveFFprobePath
			if tool == "ffmpeg" {
				resolve = ResolveFFmpegPath
			}
			resolved := resolve("", "")
			if strings.EqualFold(resolved, shim) || isChocolateyShim(resolved) {
				t.Fatalf("did not unwrap %s: %s", shim, resolved)
			}
			if got := resolve("", shim); got != resolved {
				t.Fatalf("explicit shim resolved to %q, want %q", got, resolved)
			}

			connected := make(chan struct{})
			release := make(chan struct{})
			var once sync.Once
			server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
				once.Do(func() { close(connected) })
				select {
				case <-release:
				case <-r.Context().Done():
				}
			}))
			defer server.Close()
			defer close(release)
			ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
			defer cancel()
			args := []string{"-loglevel", "fatal", "-show_format", server.URL + "/test.mkv"}
			if tool == "ffmpeg" {
				args = []string{"-loglevel", "fatal", "-i", server.URL + "/test.mkv", "-f", "null", "-"}
			}
			cmd := util.NewCmdCtx(ctx, resolved, args...)
			var stdout, stderr bytes.Buffer
			cmd.Stdout, cmd.Stderr = &stdout, &stderr
			cmd.WaitDelay = 2 * time.Second // Bound even a regression; threshold below is stricter.
			if err := cmd.Start(); err != nil {
				t.Fatal(err)
			}
			select {
			case <-connected:
			case <-ctx.Done():
				_ = cmd.Wait()
				t.Fatal("tool did not connect to the synthetic source")
			}
			start := time.Now()
			cancel()
			err := cmd.Wait()
			elapsed := time.Since(start)
			if err == nil || elapsed > time.Second {
				t.Fatalf("cancel: elapsed=%v err=%v", elapsed, err)
			}
			t.Logf("%s: cancel completed in %v", resolved, elapsed)
		})
	}
}
