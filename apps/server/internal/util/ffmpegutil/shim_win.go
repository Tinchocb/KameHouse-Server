//go:build windows

package ffmpegutil

import (
	"bytes"
	"context"
	"errors"
	"io"
	"kamehouse/internal/util"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"
)

// CommandContext kills the shim, not its child. The child can keep stdout/stderr
// open and make Wait outlive the context deadline. Ask identified Chocolatey
// shims for their target without starting it; keep ordinary binaries untouched.
// This runs only after the resolver has accepted the original executable.
func resolveToolExecutable(path string) string {
	if !isChocolateyShim(path) {
		return path
	}
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
	defer cancel()
	cmd := util.NewCmdCtx(ctx, path, "--shimgen-help")
	cmd.WaitDelay = 250 * time.Millisecond
	out, err := cmd.CombinedOutput()
	// ShimGen reports help with exit code -1, even when the output is valid.
	var exitErr *exec.ExitError
	if ctx.Err() != nil || (err != nil && !errors.As(err, &exitErr)) {
		return path
	}
	target := shimHelpTarget(string(out))
	if !filepath.IsAbs(target) || !strings.EqualFold(filepath.Base(target), filepath.Base(path)) ||
		strings.EqualFold(filepath.Clean(target), filepath.Clean(path)) {
		return path
	}
	info, err := os.Stat(target)
	if err != nil || !info.Mode().IsRegular() || isChocolateyShim(target) {
		return path
	}
	return filepath.Clean(target)
}

func isChocolateyShim(path string) bool {
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer f.Close()
	// ShimGen's version-resource description is UTF-16LE. Bound reads so normal
	// FFmpeg binaries (often hundreds of MB) are never loaded just to resolve a path.
	const maxShimSize = 4 << 20
	info, err := f.Stat()
	if err != nil || !info.Mode().IsRegular() || info.Size() > maxShimSize {
		return false
	}
	data, err := io.ReadAll(io.LimitReader(f, maxShimSize))
	if err != nil {
		return false
	}
	var marker []byte
	for _, c := range []byte("ShimGen generated shim") {
		marker = append(marker, c, 0)
	}
	return bytes.HasPrefix(data, []byte("MZ")) && bytes.Contains(data, marker)
}

func shimHelpTarget(help string) string {
	if !strings.Contains(help, "generated by Chocolatey's ShimGenerator") {
		return ""
	}
	var target string
	for _, line := range strings.Split(help, "\n") {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, "command (optional):") && line != "command (optional): ''" {
			return "" // Bypassing a shim with injected arguments would change behavior.
		}
		if strings.HasPrefix(line, "Target: '") && strings.HasSuffix(line, "'") {
			target = strings.TrimSuffix(strings.TrimPrefix(line, "Target: '"), "'")
		}
	}
	return target
}
